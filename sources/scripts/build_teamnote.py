def braced(text, pos):
    while text[pos].isspace():
        pos += 1
    if text[pos] != '{':
        raise ValueError(text[pos:pos + 50])
    start, depth = pos + 1, 1
    pos += 1
    while depth:
        if text[pos] == '{':
            depth += 1
        elif text[pos] == '}':
            depth -= 1
        pos += 1
    return text[start:pos - 1], pos



def section_heading(title):
    global section_number, subsection_number
    section_number += 1
    subsection_number = 0
    return Paragraph(escape(f'{section_number}. {title}'), section_style)


def subheading(title):
    global subsection_number
    subsection_number += 1
    return Paragraph(escape(f'{section_number}.{subsection_number} {title}'), heading_style)


class CodeLine(Flowable):
    """Single physical line; fixed ASCII cells plus Korean font fallback."""
    def __init__(self, text, continued=False, keep=False):
        Flowable.__init__(self)
        self.text, self.continued = text, continued
        self.width, self.height = COL, 10.0 if text.strip() else 3
        self.keepWithNext = keep

    def draw(self):
        x = 0
        self.canv.setFillColor(colors.HexColor('#263541'))
        for char in self.text:
            font = 'Code' if ord(char) < 128 else 'Body'
            self.canv.setFont(font, 8.5)
            self.canv.drawString(x, 1.7, char)
            x += pdfmetrics.stringWidth(char, font, 8.5)


def code_lines(text):
    lines = []
    for line in text.expandtabs(4).splitlines():
        chunks, current, width = [], '', 0
        for char in line:
            font = 'Code' if ord(char) < 128 else 'Body'
            w = pdfmetrics.stringWidth(char, font, 8.5)
            if width + w > COL - 5:
                chunks.append(current)
                current = '    | '
                width = pdfmetrics.stringWidth(current, 'Code', 8.5)
            current += char
            width += w
        chunks.append(current)
        lines.extend(CodeLine(chunk, i > 0) for i, chunk in enumerate(chunks))
    # Keep decorators and signatures with at least the next physical line.
    for i, line in enumerate(lines[:-1]):
        if line.text.strip().startswith(('def ', 'class ', '@')):
            line.keepWithNext = True
    return lines


class TeamnoteDoc(BaseDocTemplate):
    def afterFlowable(self, flowable):
        if (isinstance(flowable, Paragraph) and flowable.style.name in ('Section', 'Heading')
                and flowable.getPlainText() != '목차'):
            level = 0 if flowable.style.name == 'Section' else 1
            text = flowable.getPlainText()
            key = 'heading-' + str(self.seq.nextf('heading'))
            self.canv.bookmarkPage(key)
            self.canv.addOutlineEntry(text, key, level=level, closed=False)
            self.notify('TOCEntry', (level, text, self.page, key))


